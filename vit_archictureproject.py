"""## Eq. 1

* Splits the image into 16×16 patches with a strided Conv2d, prepends a learnable class token, and adds learnable position embeddings

### Patch Embedding CLass
"""

class PatchEmbedding(nn.Module):
  def __init__(self,in_channels=3,patch_size=16, embedding_dim=768,batch_size=32):
    super().__init__()

    self.first_layer = nn.Conv2d(
        in_channels=in_channels,
        out_channels =embedding_dim,
        kernel_size =patch_size,
        stride =patch_size
    )

    self.flatten = nn.Flatten(start_dim=2,
                                   end_dim=3)

    self.class_token = nn.Parameter(torch.ones(1,1,embedding_dim),
                                    requires_grad=True)
    num_patches = (224 // patch_size) ** 2
    self.positional_embedding = nn.Parameter(torch.ones(1,num_patches+1,embedding_dim),
                                             requires_grad=True)

  def forward(self,x):
    batch_size = x.shape[0]
    x = self.first_layer(x)
    x = self.flatten(x)
    x = x.permute(0, 2, 1)
    class_token = self.class_token.expand(batch_size, -1, -1)
    x_class_token= torch.cat((class_token, x),dim=1)
    positional_embedding = self.positional_embedding +x_class_token

    return positional_embedding

