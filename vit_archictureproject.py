"""## 	Eq. 2 + 3

* Stacks the MSA and MLP blocks ×12

###TransformerEncoderBlock
"""

class TransformerEncoderBlock(nn.Module):
  def __init__(self):
    super().__init__()

    self.msa_block= MSABlock()
    self.mlp_block = MLPBlock()

  def forward(self, x):
    ## apply MSA and add residual connections
    x = self.msa_block(x) +x
    ## apply MPL and add residual connections
    x =  self.mlp_block(x) + x
    return x

