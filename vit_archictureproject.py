"""##	Eq. 3

*	LayerNorm → MLP (Linear → GELU → Linear), with a residual connection

### MLP
"""

class MLPBlock(nn.Module):
  def __init__(self,embedding_dim=768, mlp_size=3072, dropout=0.1):
    super().__init__()
    # Layer Norm
    self.layer_norm = nn.LayerNorm(normalized_shape=embedding_dim)
    self.mlp = nn.Sequential(
      nn.Linear(in_features=embedding_dim, out_features=mlp_size),   # 768 → 3072
      nn.GELU(),
      nn.Dropout(p=dropout),
      nn.Linear(in_features=mlp_size, out_features=embedding_dim),   # 3072 → 768
      nn.Dropout(p=dropout)
  )

  def forward(self, x):
     return self.mlp(self.layer_norm(x))

